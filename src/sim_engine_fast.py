def generate_clustered_sites(num_sites, nucleus_radius_um, cluster_probs,
                             cluster_radius_nm=150.0, num_synthetic=0,
                             synthetic_radius_nm=150.0, site_rng=None):
    # Level 3: site_rng is either None (falls back to np.random module for
    # backwards compatibility) or a numpy Generator / the np.random module.
    # Both expose .normal / .random with identical signatures, so this is a
    # pure drop-in substitution.
    if site_rng is None:
        site_rng = np.random
    cluster_radius_um = cluster_radius_nm / 1000.0
    synthetic_radius_um = synthetic_radius_nm / 1000.0
    sites, cluster_ids, is_synthetic = [], [], []
    cid = 0

    total_p = sum(cluster_probs.values())
    if total_p == 0 and num_sites > 0:
        norm = {1: 1.0}
    elif total_p > 0:
        norm = {k: v / total_p for k, v in cluster_probs.items()}
    else:
        norm = {}

    for size, prob in norm.items():
        n_clusters = int(int(num_sites * prob) / size)
        for _ in range(n_clusters):
            center = site_rng.normal(size=3)
            center /= np.linalg.norm(center)
            center *= (site_rng.random() ** (1.0 / 3)) * nucleus_radius_um
            for _ in range(size):
                off = site_rng.normal(size=3)
                off /= np.linalg.norm(off)
                off *= (site_rng.random() ** (1.0 / 3)) * cluster_radius_um
                pos = center + off
                if np.linalg.norm(pos) > nucleus_radius_um:
                    pos = pos / np.linalg.norm(pos) * nucleus_radius_um
                sites.append(pos)
                cluster_ids.append(cid)
                is_synthetic.append(False)
            cid += 1

    while len(sites) < num_sites:
        pos = site_rng.normal(size=3)
        pos /= np.linalg.norm(pos)
        pos *= (site_rng.random() ** (1.0 / 3)) * nucleus_radius_um
        sites.append(pos)
        cluster_ids.append(cid)
        is_synthetic.append(False)
        cid += 1

    if num_synthetic > 0:
        sc = site_rng.normal(size=3)
        sc /= np.linalg.norm(sc)
        sc *= (site_rng.random() ** (1.0 / 3)) * nucleus_radius_um * 0.7
        syn_cid = cid
        for _ in range(num_synthetic):
            off = site_rng.normal(size=3)
            off /= np.linalg.norm(off)
            off *= (site_rng.random() ** (1.0 / 3)) * synthetic_radius_um
            pos = sc + off
            if np.linalg.norm(pos) > nucleus_radius_um:
                pos = pos / np.linalg.norm(pos) * nucleus_radius_um
            sites.append(pos)
            cluster_ids.append(syn_cid)
            is_synthetic.append(True)

    return np.array(sites), np.array(cluster_ids), np.array(is_synthetic)


def assign_site_strengths(num_sites, cluster_ids, strength_multipliers,
                          strength_percentages, is_synthetic,
                          synthetic_strength=1.0, cluster_correlated=False,
                          site_rng=None):
    # Level 3: strengths are a SITE property (defining the landscape), so they
    # flow through site_rng to stay invariant across concentrations.
    if site_rng is None:
        site_rng = np.random
    site_strengths = np.zeros(num_sites)
    # synthetic_strength may be scalar (broadcast to every synthetic site) or
    # a 1-D array of length equal to the number of synthetic sites (per-site
    # multiplier; element i -> i-th synthetic site in generation order).
    num_synth = int(np.sum(is_synthetic))
    if num_synth > 0:
        ss_arr = np.atleast_1d(np.asarray(synthetic_strength, dtype=float))
        if ss_arr.size not in (1, num_synth):
            raise ValueError(
                "synthetic_strength has length %d but there are %d synthetic "
                "sites; pass either a scalar or an array of length %d."
                % (ss_arr.size, num_synth, num_synth)
            )
        site_strengths[is_synthetic] = ss_arr  # broadcasts if size 1
    endogenous_mask = ~is_synthetic
    num_endogenous = np.sum(endogenous_mask)
    if num_endogenous > 0:
        total_pct = sum(strength_percentages)
        if total_pct == 0:
            probs = [1.0 / len(strength_multipliers)] * len(strength_multipliers)
        else:
            probs = [p / total_pct for p in strength_percentages]
        if cluster_correlated:
            endogenous_clusters = np.unique(cluster_ids[endogenous_mask])
            cluster_strengths_dict = {}
            for c in endogenous_clusters:
                cluster_strengths_dict[c] = site_rng.choice(strength_multipliers, p=probs)
            for idx in np.where(endogenous_mask)[0]:
                site_strengths[idx] = cluster_strengths_dict[cluster_ids[idx]]
        else:
            eidx = np.where(endogenous_mask)[0]
            site_strengths[eidx] = site_rng.choice(
                strength_multipliers, size=num_endogenous, p=probs)
    return site_strengths

def build_site_layout(
    num_binding_sites,
    nucleus_diameter_nm,
    cluster_distribution,
    cluster_radius_nm,
    num_synthetic_sites,
    synthetic_strength,
    synthetic_cluster_radius_nm,
    strength_multipliers,
    strength_percentages,
    cluster_correlated_strength,
    bs_diff_mean,
    bs_diff_std,
    capture_radius_nm,
    site_rng=None,
):
    """
    Build the full site-layout payload consumed by run_full_simulation's
    `precomputed_sites` path.
 
    Returns
    -------
    dict with keys:
        sites          : (N, 3) float64 positions in micrometres, clamped
                         to (nucleus_radius - capture_radius).
        cluster_ids    : (N,)   int      cluster membership.
        is_synthetic   : (N,)   bool     synthetic-site mask.
        site_strengths : (N,)   float64  per-site strength multiplier.
        cluster_D      : (K,)   float64  diffusion coefficient per cluster
                                          (µm²/s, floored at 0.005).
 
    Notes
    -----
    - If site_rng is None, falls back to the module-level np.random state
      (matches the Pass-1 back-compat contract for the other site helpers).
    - The boundary clamp step is critical: it's the same clamp
      run_full_simulation applies before freezing site positions. Without
      it, a follower loading the cache would see uncorrected positions and
      diverge from what the leader's engine used.
    - cluster_D is drawn per UNIQUE cluster id, in the order produced by
      np.unique — the same order run_full_simulation uses to index into it.
    - synthetic_strength may be a scalar (applied to all synthetic sites)
      or a 1-D array of length num_synthetic_sites (per-site multiplier).
    """
    rng = site_rng if site_rng is not None else np.random
 
    nucleus_radius_um = (nucleus_diameter_nm / 2.0) / 1000.0
    capture_radius_um = capture_radius_nm / 1000.0
 
    # 1. Site positions + cluster assignment.
    sites, cluster_ids, is_synthetic = generate_clustered_sites(
        num_binding_sites, nucleus_radius_um, cluster_distribution,
        cluster_radius_nm=cluster_radius_nm,
        num_synthetic=num_synthetic_sites,
        synthetic_radius_nm=synthetic_cluster_radius_nm,
        site_rng=site_rng,
    )
 
    # 2. Strengths.
    if strength_multipliers is None:
        strength_multipliers = [1.0]
    if strength_percentages is None:
        strength_percentages = [100.0]
    site_strengths = assign_site_strengths(
        len(sites), cluster_ids, strength_multipliers, strength_percentages,
        is_synthetic, synthetic_strength, cluster_correlated_strength,
        site_rng=site_rng,
    )
 
    # 3. Boundary clamp — sites outside (radius - capture) get pulled in so
    #    the capture sphere around each site stays inside the nucleus. This
    #    mutates `sites` in place, matching run_full_simulation's behaviour.
    inner_radius = nucleus_radius_um - capture_radius_um
    s_dists = np.linalg.norm(sites, axis=1)
    m_out = s_dists > inner_radius
    if np.any(m_out):
        sites[m_out] *= (inner_radius / s_dists[m_out])[:, np.newaxis]
 
    # 4. Per-cluster diffusion coefficients. np.unique returns sorted unique
    #    values; run_full_simulation indexes cluster_D by the same ordering.
    unique_clusters = np.unique(cluster_ids)
    num_clusters = len(unique_clusters)
    cluster_D = np.maximum(
        0.005,
        rng.normal(bs_diff_mean, bs_diff_std, num_clusters),
    )
 
    return {
        'sites':          sites,
        'cluster_ids':    cluster_ids,
        'is_synthetic':   is_synthetic,
        'site_strengths': site_strengths,
        'cluster_D':      cluster_D,
    }

def generate_all_fbm_steps_dh(total_steps, num_clusters, cluster_D, hurst, sim_dt_s,
                              site_rng=None):
    # Level 3: fBm cluster motion is a SITE property (defines landscape
    # dynamics), so all draws flow through site_rng.
    if site_rng is None:
        site_rng = np.random
    n = int(total_steps)
    H = float(np.clip(hurst, 0.01, 0.99))
    step_stds = np.sqrt(2.0 * np.maximum(cluster_D, 0.0) * sim_dt_s)
    if n < 2 or num_clusters == 0:
        out = np.zeros((n, num_clusters, 3))
        for d in range(3):
            out[:, :, d] = site_rng.normal(size=(n, num_clusters)) * step_stds[np.newaxis, :]
        return out
    N = 2 * n
    k = np.arange(n + 1, dtype=float)
    autocov = 0.5 * (np.abs(k - 1) ** (2.0 * H) - 2.0 * np.abs(k) ** (2.0 * H) + np.abs(k + 1) ** (2.0 * H))
    r = np.empty(N)
    r[:n + 1] = autocov
    r[n + 1:] = autocov[1:n][::-1]
    lam = np.fft.fft(r).real
    lam = np.maximum(lam, 0.0)
    n_series = num_clusters * 3
    w = np.zeros((n_series, N), dtype=complex)
    w[:, 0] = np.sqrt(lam[0] / N) * site_rng.normal(size=n_series)
    w[:, n] = np.sqrt(lam[n] / N) * site_rng.normal(size=n_series)
    scale_mid = np.sqrt(lam[1:n] / (2.0 * N))
    w[:, 1:n] = scale_mid[np.newaxis, :] * (
        site_rng.normal(size=(n_series, n - 1)) + 1j * site_rng.normal(size=(n_series, n - 1)))
    w[:, n + 1:] = np.conj(w[:, 1:n][:, ::-1])
    fgn = np.fft.fft(w, axis=1).real[:, :n]
    fgn = fgn.reshape(num_clusters, 3, n).transpose(2, 0, 1)
    steps = fgn * step_stds[np.newaxis, :, np.newaxis]
    return steps


def generate_fbm_step(prev_step, hurst, num_clusters, cluster_D, sim_dt_s,
                      site_rng=None):
    if site_rng is None:
        site_rng = np.random
    step_std = np.sqrt(2 * cluster_D * sim_dt_s)
    new_random = site_rng.normal(0, 1, (num_clusters, 3))
    rho = 2.0 ** (2.0 * hurst - 1.0) - 1.0
    rho = np.clip(rho, -0.99, 0.99)
    if prev_step is not None:
        prev_norms = np.linalg.norm(prev_step, axis=1, keepdims=True)
        prev_norms = np.where(prev_norms > 1e-10, prev_norms, 1.0)
        prev_direction = prev_step / prev_norms
        combined = rho * prev_direction + np.sqrt(1.0 - rho ** 2) * new_random
    else:
        combined = new_random
    step = combined * step_std[:, np.newaxis]
    return step


def _run_physics_step(
    pos, states, sites, sites_base, site_occupancy, bound_site_indices, unbind_times,
    current_ds, sample_ds, cluster_D, site_cluster_idx, site_strengths,
    p_fi, p_if, p_fns, p_ins, p_ns_out, p_dest_free, p_dest_inter,
    bs_diff_mean, bs_diff_std, bs_jiggle_std, bs_hurst,
    radius_um, capture_radius_um, inner_radius, sim_dt_s, current_time,
    res_time_mean, res_time_std, k_on_prob, num_clusters,
    prev_cluster_step,
    enable_cooperativity, coop_strength, coop_hill, cluster_occupancy_count,
    two_state_mode=False, check_binding=True, cached_tree=None,
    precomputed_cluster_step=None,
    site_rng=None, mol_rng=None,
):
    # Level 3: state transitions, unbinding-state choice, diffusion, binding
    # dice, bind shuffle, and residence-time draw are all MOLECULE events and
    # route through mol_rng. Site jiggle routes through site_rng. The fallback
    # generate_fbm_step is site motion -> site_rng.
    if site_rng is None:
        site_rng = np.random
    if mol_rng is None:
        mol_rng = np.random
    # State transitions
    changed_indices = []
    if two_state_mode:
        mask_0 = (states == 0)
        if np.any(mask_0):
            r = mol_rng.random(size=np.sum(mask_0))
            to_ns = r < p_fns
            idx = np.where(mask_0)[0]
            ns_changers = idx[to_ns]
            states[ns_changers] = 3
            if len(ns_changers) > 0:
                changed_indices.append(ns_changers)
        mask_3 = (states == 3)
        if np.any(mask_3):
            r = mol_rng.random(size=np.sum(mask_3))
            leaving = r < p_ns_out
            idx = np.where(mask_3)[0]
            leavers = idx[leaving]
            states[leavers] = 0
            if len(leavers) > 0:
                changed_indices.append(leavers)
    else:
        mask_0 = (states == 0)
        if np.any(mask_0):
            r = mol_rng.random(size=np.sum(mask_0))
            to_inter = r < p_fi
            to_ns = (r >= p_fi) & (r < (p_fi + p_fns))
            idx = np.where(mask_0)[0]
            changed_0 = np.concatenate([idx[to_inter], idx[to_ns]])
            states[idx[to_inter]] = 1
            states[idx[to_ns]] = 3
            if len(changed_0) > 0:
                changed_indices.append(changed_0)
        mask_1 = (states == 1)
        if np.any(mask_1):
            r = mol_rng.random(size=np.sum(mask_1))
            to_free = r < p_if
            to_ns = (r >= p_if) & (r < (p_if + p_ins))
            idx = np.where(mask_1)[0]
            changed_1 = np.concatenate([idx[to_free], idx[to_ns]])
            states[idx[to_free]] = 0
            states[idx[to_ns]] = 3
            if len(changed_1) > 0:
                changed_indices.append(changed_1)
        mask_3 = (states == 3)
        if np.any(mask_3):
            r = mol_rng.random(size=np.sum(mask_3))
            leaving = r < p_ns_out
            idx = np.where(mask_3)[0]
            leavers = idx[leaving]
            new_dest = mol_rng.choice([0, 1], size=len(leavers), p=[p_dest_free, p_dest_inter])
            states[leavers] = new_dest
            if len(leavers) > 0:
                changed_indices.append(leavers)

    if changed_indices:
        all_changed = np.concatenate(changed_indices)
        current_ds[all_changed] = sample_ds(states[all_changed])

    # Binding site motion
    sites_moved = False
    current_cluster_step = None
    if bs_diff_mean > 0 or bs_diff_std > 0 or bs_jiggle_std > 0:
        sites_moved = True
        if bs_diff_mean > 0 or bs_diff_std > 0:
            if precomputed_cluster_step is not None:
                cluster_step = precomputed_cluster_step
            else:
                cluster_step = generate_fbm_step(
                    prev_cluster_step, bs_hurst, num_clusters, cluster_D, sim_dt_s,
                    site_rng=site_rng)
            sites_base += cluster_step[site_cluster_idx]
            current_cluster_step = cluster_step
        s_dists = np.linalg.norm(sites_base, axis=1)
        m_out = s_dists > inner_radius
        sites_base[m_out] *= (inner_radius / s_dists[m_out])[:, np.newaxis]
        if bs_jiggle_std > 0:
            sites[:] = sites_base + site_rng.normal(0, bs_jiggle_std, sites.shape)
            # Clamp sites to radius_um after jiggle
            _sd = np.linalg.norm(sites, axis=1)
            _so = _sd > radius_um
            if np.any(_so):
                sites[_so] *= (radius_um / _sd[_so])[:, np.newaxis]
        else:
            sites[:] = sites_base

    # Unbinding
    mask_bound = (states == 2)
    if np.any(mask_bound):
        releasing = mask_bound & (unbind_times <= current_time)
        if np.any(releasing):
            rel_idx = np.where(releasing)[0]
            target_sites = bound_site_indices[rel_idx]
            valid_releases = (site_occupancy[target_sites] == rel_idx)
            final_target_sites = target_sites[valid_releases]
            final_rel_idx = rel_idx[valid_releases]
            site_occupancy[final_target_sites] = -1
            if enable_cooperativity:
                c_indices = site_cluster_idx[final_target_sites]
                np.subtract.at(cluster_occupancy_count, c_indices, 1)
                cluster_occupancy_count[cluster_occupancy_count < 0] = 0
            if two_state_mode:
                states[final_rel_idx] = mol_rng.choice(
                    [0, 3], size=len(final_rel_idx), p=[p_dest_free, 1.0 - p_dest_free])
            else:
                states[final_rel_idx] = mol_rng.choice(
                    [0, 1], size=len(final_rel_idx), p=[p_dest_free, p_dest_inter])
            bound_site_indices[final_rel_idx] = -1
            current_ds[final_rel_idx] = sample_ds(states[final_rel_idx])

    # Diffusion
    mobile_mask = (states != 2)
    mobile_idx = np.where(mobile_mask)[0]
    if len(mobile_idx) > 0:
        pos[mobile_idx] += mol_rng.normal(
            0, np.sqrt(2 * current_ds[mobile_idx] * sim_dt_s)[:, np.newaxis], (len(mobile_idx), 3))
    bound_mask = (states == 2)
    if np.any(bound_mask):
        pos[bound_mask] = sites[bound_site_indices[bound_mask]]

    # Binding check
    new_tree = cached_tree
    if check_binding and len(mobile_idx) > 0:
        if cached_tree is None or sites_moved:
            new_tree = cKDTree(sites)
        dists, s_ids = new_tree.query(pos[mobile_idx], k=1, distance_upper_bound=capture_radius_um)
        valid_check = (dists < capture_radius_um) & (s_ids < len(sites))
        if np.any(valid_check):
            cand_mol = mobile_idx[valid_check]
            cand_site = s_ids[valid_check]
            site_free = (site_occupancy[cand_site] == -1)
            cand_mol = cand_mol[site_free]
            cand_site = cand_site[site_free]
            if len(cand_mol) > 0:
                if enable_cooperativity:
                    c_ids = site_cluster_idx[cand_site]
                    n_occ = cluster_occupancy_count[c_ids]
                    mult = 1.0 + (coop_strength * n_occ) ** coop_hill
                    probs = np.minimum(1.0, k_on_prob * mult)
                else:
                    probs = k_on_prob
                binds = mol_rng.random(len(cand_mol)) < probs
                cand_mol = cand_mol[binds]
                cand_site = cand_site[binds]
                if len(cand_mol) > 0:
                    shuffle = mol_rng.permutation(len(cand_mol))
                    cand_mol = cand_mol[shuffle]
                    cand_site = cand_site[shuffle]
                    _, unique_site_idx = np.unique(cand_site, return_index=True)
                    cand_mol = cand_mol[unique_site_idx]
                    cand_site = cand_site[unique_site_idx]
                    states[cand_mol] = 2
                    bound_site_indices[cand_mol] = cand_site
                    pos[cand_mol] = sites[cand_site]
                    site_occupancy[cand_site] = cand_mol
                    current_ds[cand_mol] = 0.0
                    if enable_cooperativity:
                        np.add.at(cluster_occupancy_count, site_cluster_idx[cand_site], 1)
                    site_str = site_strengths[cand_site]
                    unbind_times[cand_mol] = current_time + np.maximum(
                        0.1, mol_rng.normal(res_time_mean * site_str, res_time_std * site_str))

    # Boundary enforcement (mobile molecules only - bound ones are at site positions)
    if len(mobile_idx) > 0:
        _bd = np.linalg.norm(pos[mobile_idx], axis=1)
        _bo = _bd > radius_um
        if np.any(_bo):
            _oi = mobile_idx[_bo]
            pos[_oi] *= (radius_um / _bd[_bo])[:, np.newaxis]
    return current_cluster_step, new_tree



def run_full_simulation(
    num_display_frames, num_binding_sites, nucleus_diam_nm, tf_concentration_nM,
    sim_dt_s, display_dt_s,
    pct_free_init, pct_inter_init, pct_ns_init,
    d_inter, d_free, d_ns,
    d_free_std, d_inter_std, d_ns_std,
    bs_diff_mean, bs_diff_std, bs_jiggle_std, bs_hurst,
    k_free_to_inter, k_inter_to_free,
    k_free_to_ns, k_inter_to_ns,
    ns_res_time,
    cluster_distribution,
    res_time_mean, res_time_std,
    capture_radius_nm, k_on_prob,
    strength_multipliers=None, strength_percentages=None,
    cluster_correlated_strength=False,
    num_synthetic_sites=0, synthetic_strength=1.0,
    synthetic_cluster_radius_nm=150.0, cluster_radius_nm=150.0,
    exposure_time_s=0.05,
    enable_cooperativity=False, coop_strength=1.0, coop_hill=1.0,
    two_state_mode=True, show_progress=False,
    binding_check_interval=1, progress_callback=None,
    sim_seed=None,
    record_step_history=False,
    # -----------------------------------------------------------------
    # Level 3: split RNG kwargs. Both default to None -> fall back to
    # np.random module so existing callers (app2.py, old scripts) work
    # unchanged. When provided they should be numpy Generator instances.
    #   site_rng : drives positions, strengths, cluster_D, fBm, jiggle
    #   mol_rng  : drives initial positions, state transitions, diffusion,
    #              binding dice, residence time
    # Level 3 also allows skipping site generation when precomputed_sites
    # is provided — a dict with keys:
    #   'sites', 'cluster_ids', 'is_synthetic',
    #   'site_strengths', 'cluster_D'
    # If passed, those arrays are used verbatim and the site_rng is NOT
    # consumed for site setup (callers are expected to have spawned a
    # separate motion RNG so per-step site dynamics stay consistent
    # between leader and follower rows).
    # -----------------------------------------------------------------
    site_rng=None, mol_rng=None,
    precomputed_sites=None,
):
    
    # === REPRODUCIBILITY: seed numpy's global RNG before anything random ===
    # Level 1/2 back-compat path: if no explicit site_rng/mol_rng were
    # provided, we fall back to the numpy global RNG and honor sim_seed
    # exactly as before. Every helper below sees site_rng is None -> uses
    # np.random, so the global seed covers them all.
    #
    # Level 3 path: when site_rng and mol_rng are explicitly provided, we
    # IGNORE sim_seed here (the caller has already seeded each generator
    # from a SeedSequence) and let every np.random.* call that was NOT
    # audit-routed (there should be none left inside the simulation loop)
    # still behave deterministically via the caller's own np.random.seed
    # up the stack.
    if site_rng is None and mol_rng is None and sim_seed is not None:
        np.random.seed(int(sim_seed))
    # Resolve defaults once so the rest of the function can pass them on
    # without worrying about None.
    _site_rng = np.random if site_rng is None else site_rng
    _mol_rng = np.random if mol_rng is None else mol_rng
    # =====================================================================



    radius_um = (nucleus_diam_nm / 2) / 1000.0
    capture_radius_um = capture_radius_nm / 1000.0

    if sim_dt_s <= 0:
        sim_dt_s = 0.013
    steps_per_display = int(display_dt_s / sim_dt_s)
    if steps_per_display < 1:
        steps_per_display = 1
    steps_per_exposure = max(1, int(exposure_time_s / sim_dt_s))

    vol_um3 = (4.0 / 3) * np.pi * (radius_um ** 3)
    num_molecules = int(((tf_concentration_nM * 1e-9) * (vol_um3 * 1e-15)) * 6.022e23)

    # -----------------------------------------------------------------
    # SITE LANDSCAPE: either load from cache (site_group leader wrote it)
    # or generate fresh using site_rng. All randomness inside the cache-
    # miss branch goes through site_rng so it's reproducible.
    # -----------------------------------------------------------------
    if precomputed_sites is not None:
        sites = precomputed_sites['sites'].copy()
        cluster_ids = precomputed_sites['cluster_ids']
        is_synthetic = precomputed_sites['is_synthetic']
        site_strengths = precomputed_sites['site_strengths']
        # cluster_D lives alongside the static site set; cache it too.
        cluster_D_cached = precomputed_sites['cluster_D']
    else:
        sites, cluster_ids, is_synthetic = generate_clustered_sites(
            num_binding_sites, radius_um, cluster_distribution,
            cluster_radius_nm=cluster_radius_nm,
            num_synthetic=num_synthetic_sites,
            synthetic_radius_nm=synthetic_cluster_radius_nm,
            site_rng=_site_rng)
        if strength_multipliers is None:
            strength_multipliers = [1.0]
        if strength_percentages is None:
            strength_percentages = [100.0]
        site_strengths = assign_site_strengths(
            len(sites), cluster_ids, strength_multipliers, strength_percentages,
            is_synthetic, synthetic_strength, cluster_correlated_strength,
            site_rng=_site_rng)
        cluster_D_cached = None  # compute below

    site_occupancy = np.full(len(sites), -1, dtype=int)

    # (strength defaults already ensured above if we hit that branch; ensure
    # them here too in case precomputed_sites path skipped over them and a
    # downstream caller still looks at them.)
    if strength_multipliers is None:
        strength_multipliers = [1.0]
    if strength_percentages is None:
        strength_percentages = [100.0]

    inner_radius = radius_um - capture_radius_um
    s_dists = np.linalg.norm(sites, axis=1)
    m_out = s_dists > inner_radius
    if np.any(m_out):
        sites[m_out] *= (inner_radius / s_dists[m_out])[:, np.newaxis]

    sites_base = sites.copy()

    unique_clusters = np.unique(cluster_ids)
    num_clusters = len(unique_clusters)
    if cluster_D_cached is not None:
        cluster_D = cluster_D_cached
    else:
        cluster_D = np.maximum(
            0.005,
            _site_rng.normal(bs_diff_mean, bs_diff_std, num_clusters))

    cluster_id_to_idx = {cid: i for i, cid in enumerate(unique_clusters)}
    site_cluster_idx = np.array([cluster_id_to_idx[cid] for cid in cluster_ids])
    cluster_occupancy_count = np.zeros(num_clusters, dtype=int)

    pos = _mol_rng.normal(size=(num_molecules, 3))
    pos /= np.linalg.norm(pos, axis=1)[:, np.newaxis]
    pos *= (_mol_rng.random(num_molecules) ** (1.0 / 3) * radius_um)[:, np.newaxis]

    if two_state_mode:
        total_pct = pct_free_init + pct_ns_init
        if total_pct == 0:
            p_dist = [1, 0]
        else:
            p_dist = [pct_free_init / total_pct, pct_ns_init / total_pct]
        states = _mol_rng.choice([0, 3], size=num_molecules, p=p_dist)
        p_dest_free = 1.0
        p_dest_inter = 0.0
    else:
        total_pct = pct_free_init + pct_inter_init + pct_ns_init
        if total_pct == 0:
            p_dist = [1, 0, 0]
        else:
            p_dist = [pct_free_init / total_pct, pct_inter_init / total_pct,
                      pct_ns_init / total_pct]
        states = _mol_rng.choice([0, 1, 3], size=num_molecules, p=p_dist)
        sum_mobile = pct_free_init + pct_inter_init
        if sum_mobile > 0:
            p_dest_free = pct_free_init / sum_mobile
            p_dest_inter = pct_inter_init / sum_mobile
        else:
            p_dest_free, p_dest_inter = 0.5, 0.5

    bound_site_indices = np.full(num_molecules, -1, dtype=int)
    unbind_times = np.zeros(num_molecules)
    p_fi = k_free_to_inter * sim_dt_s
    p_if = k_inter_to_free * sim_dt_s
    p_fns = k_free_to_ns * sim_dt_s
    p_ins = k_inter_to_ns * sim_dt_s
    p_ns_out = (1.0 / ns_res_time) * sim_dt_s if ns_res_time > 0 else 1.0

    def sample_ds(state_arr):
        ds = np.zeros_like(state_arr, dtype=float)
        m0 = (state_arr == 0)
        ds[m0] = np.maximum(0, _mol_rng.normal(d_free, d_free_std,
                                                size=np.sum(m0)))
        if not two_state_mode:
            m1 = (state_arr == 1)
            ds[m1] = np.maximum(0, _mol_rng.normal(d_inter, d_inter_std,
                                                    size=np.sum(m1)))
        m_ns = (state_arr == 3)
        ds[m_ns] = np.maximum(0, _mol_rng.normal(d_ns, d_ns_std,
                                                   size=np.sum(m_ns)))
        return ds

    current_ds = sample_ds(states)
    exposure_data = {f: None for f in range(num_display_frames)}
    # Level 2 repro: optional flat per-sim-step history covering EVERY physics
    # step (advance + exposure). Enables re-binning to a different display_dt
    # / exposure_time_ms without re-running the simulation.
    step_history = [] if record_step_history else None
    current_time = 0.0
    bs_hurst = np.clip(bs_hurst, 0.01, 0.99)
    prev_cluster_step = None

    # ---- Per-frame fBm with exact conditioning at boundaries ----
    _use_dh_fbm = (bs_diff_mean > 0 or bs_diff_std > 0)
    precomputed_bs_steps = None
    _frame_step_base = 0
    if _use_dh_fbm:
        _step_stds = np.sqrt(2.0 * np.maximum(cluster_D, 0.0) * sim_dt_s)
        _H = float(bs_hurst)
        _r1 = 0.5 * (2.0 ** (2.0 * _H) - 2.0)  # fGn autocovariance at lag 1

    physics_step = 0
    binding_check_interval = max(1, int(binding_check_interval))
    sites_are_static = (bs_diff_mean <= 0 and bs_diff_std <= 0
                        and bs_jiggle_std <= 0)
    cached_tree = cKDTree(sites) if sites_are_static else None

    for display_frame in range(num_display_frames):
        # Generate fBm steps for this frame only
        if _use_dh_fbm:
            _nf = steps_per_display + 2
            _dh = generate_all_fbm_steps_dh(
                _nf, num_clusters, cluster_D, bs_hurst, sim_dt_s,
                site_rng=_site_rng)
            if display_frame > 0 and prev_cluster_step is not None:
                # Exact Gaussian bridge: r(1)*prev + sqrt(1-r(1)^2)*std*Z
                _bridge = (_r1 * prev_cluster_step
                           + np.sqrt(1.0 - _r1 ** 2)
                           * _step_stds[:, np.newaxis]
                           * _site_rng.normal(size=prev_cluster_step.shape))
                # Condition DH block on first element = bridge
                _k = np.arange(1, _nf, dtype=float)
                _rk = 0.5 * (np.abs(_k - 1) ** (2 * _H)
                             - 2 * np.abs(_k) ** (2 * _H)
                             + np.abs(_k + 1) ** (2 * _H))
                _dh[1:] += _rk[:, np.newaxis, np.newaxis] * (
                    _bridge[np.newaxis, :, :] - _dh[0:1, :, :])
                _dh[0] = _bridge
            precomputed_bs_steps = _dh
            _frame_step_base = physics_step

        # ---------------------------------------------------------------
        # Unified per-display-frame loop. Each frame runs EXACTLY
        # steps_per_display physics steps. The exposure window sits at
        # the START of the frame: the first steps_per_exposure steps
        # snapshot into exposure_data[display_frame]. The remaining
        # (steps_per_display - steps_per_exposure) steps just advance
        # physics. This makes step_history a uniform grid of length
        # num_display_frames * steps_per_display, where frame df starts
        # at index df * steps_per_display — which is exactly what
        # sim_repro.rebin_to_exposures assumes.
        # ---------------------------------------------------------------
        _exp_pos_buf    = []
        _exp_states_buf = []
        _exp_sites_buf  = []
        _exp_occ_buf    = []

        for frame_step in range(steps_per_display):
            in_exposure_window = (frame_step < steps_per_exposure)

            if in_exposure_window:
                # float32 halves size vs float64; astype() makes a copy
                _exp_pos_buf.append(pos.astype(np.float32))
                _exp_states_buf.append(states.copy())
                _exp_sites_buf.append(sites.astype(np.float32))
                _exp_occ_buf.append((site_occupancy >= 0).copy())

            if step_history is not None:
                step_history.append({
                    'pos': pos.copy(), 'states': states.copy(),
                    'sites': sites.copy(),
                    'occupancy': (site_occupancy >= 0).copy()})

            # Binding check policy: always check inside the exposure
            # window (matches the old exposure-loop behavior); honor
            # binding_check_interval outside it (matches the old
            # advance-loop behavior).
            check_binding = (in_exposure_window
                             or (physics_step % binding_check_interval == 0))

            _dh_step = (
                precomputed_bs_steps[physics_step - _frame_step_base]
                if precomputed_bs_steps is not None
                and (physics_step - _frame_step_base) < len(precomputed_bs_steps)
                else None)
            prev_cluster_step, cached_tree = _run_physics_step(
                pos, states, sites, sites_base, site_occupancy,
                bound_site_indices, unbind_times,
                current_ds, sample_ds, cluster_D, site_cluster_idx,
                site_strengths,
                p_fi, p_if, p_fns, p_ins, p_ns_out,
                p_dest_free, p_dest_inter,
                bs_diff_mean, bs_diff_std, bs_jiggle_std, bs_hurst,
                radius_um, capture_radius_um, inner_radius, sim_dt_s,
                current_time,
                res_time_mean, res_time_std, k_on_prob, num_clusters,
                prev_cluster_step,
                enable_cooperativity, coop_strength, coop_hill,
                cluster_occupancy_count,
                two_state_mode=two_state_mode,
                check_binding=check_binding, cached_tree=cached_tree,
                precomputed_cluster_step=_dh_step,
                site_rng=_site_rng, mol_rng=_mol_rng)
            current_time += sim_dt_s
            physics_step += 1

        if _exp_pos_buf:
            _ps = np.stack(_exp_pos_buf)    # (steps, N, 3) float32
            _ss = np.stack(_exp_states_buf)
            _si = np.stack(_exp_sites_buf)
            _oo = np.stack(_exp_occ_buf)
            exposure_data[display_frame] = {
                'pos_steps':     _ps.astype(np.float32),               # (steps, N, 3)
                'modal_states':  stats.mode(_ss, axis=0, keepdims=False)[0].astype(np.int8),
                'site_centroid': _si.mean(axis=0).astype(np.float32),
                'any_occupied':  _oo.any(axis=0),
            }

        if progress_callback:
            progress_callback(display_frame + 1, num_display_frames)

    return exposure_data, num_molecules, site_strengths, is_synthetic, \
        steps_per_exposure, step_history




